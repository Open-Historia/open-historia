// Writes src/runtime/generated/stockRegionIds.js: the id of every region of the
// stock world, the GADM map a world map starts from. The map editor's
// save-time border cleanup reads it to tell a stock region nobody has reshaped
// from a region that is the map's own (src/Editor/shapeAuthority.js).
//
// The ids are read from the world itself, so the map files have to be there:
// scripts/fetch-map-assets.mjs downloads the desktop's
// (public/assets/regions-seed.geojson). The website and the Android app carry
// a lighter copy of the same world with, at the time of writing, one region
// fewer; any further copy named on the command line is read too and the table
// is every id any of them has.
//
// Usage:
//   node scripts/build-stock-region-ids.mjs [more regions files ...]
//   node scripts/build-stock-region-ids.mjs --check     exit 1 if the table is not what the files give
//
// Run it again whenever the stock world's regions change (a new
// regions-seed in scripts/map-assets.json). A region the table does not know
// is taken for the map's own and swept on a first save, which is slower and
// marks it reshaped, but loses nothing.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const OUT = path.join(root, "src", "runtime", "generated", "stockRegionIds.js");
const DEFAULT_SOURCE = path.join(root, "public", "assets", "regions-seed.geojson");

const args = process.argv.slice(2);
const check = args.includes("--check");
const sources = [DEFAULT_SOURCE, ...args.filter((arg) => !arg.startsWith("--")).map((file) => path.resolve(file))];

const ids = new Set();
for (const file of sources) {
  if (!fs.existsSync(file)) {
    console.error(`${file} is not there. Run node scripts/fetch-map-assets.mjs first.`);
    process.exit(1);
  }
  const collection = JSON.parse(fs.readFileSync(file, "utf8"));
  let read = 0;
  for (const feature of collection.features ?? []) {
    const id = feature?.properties?.id ?? feature?.id;
    if (id == null || String(id) === "") continue;
    // The table is written as one comma-separated string.
    if (String(id).includes(",")) throw new Error(`${file}: the id ${JSON.stringify(id)} has a comma in it`);
    ids.add(String(id));
    read += 1;
  }
  console.log(`${path.relative(root, file)}: ${read} regions`);
}

const sorted = [...ids].sort();
const text = [
  "/* AUTO-GENERATED by scripts/build-stock-region-ids.mjs — do not edit. */",
  "// The id of every region of the stock world (the GADM map a world map starts",
  "// from), desktop and web copies together. Read by the map editor's save-time",
  "// border cleanup (src/Editor/shapeAuthority.js).",
  `export const STOCK_REGION_IDS = new Set(${JSON.stringify(sorted.join(","))}.split(","));`,
  "",
].join("\n");

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("src/runtime/generated/stockRegionIds.js is not what these files give. Run node scripts/build-stock-region-ids.mjs.");
    process.exit(1);
  }
  console.log(`up to date: ${sorted.length} ids`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(root, OUT)}: ${sorted.length} ids`);
}
