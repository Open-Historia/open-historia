// Bundles the built-in "default" scenario (server/seed/default) into a single
// JS module the WEB build imports so a fresh browser can seed its IndexedDB
// library with a playable scenario. Runs only from `npm run build:web` (and
// dev:web); the output dir is git-ignored and is never imported by the local
// build, so no seed data ships in the downloaded app.
//
// The scenario's own map (regions.geojson, a few MB) is not inlined into the
// seed module — it is copied beside it and referenced by URL from a tiny
// generated meta module, so Vite emits it as a static asset the web store
// fetches on demand (defaultScenarioMeta.js: builtInMap + regionsUrl).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import url from "node:url";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "server", "seed", "default");
const OUT_DIR = path.join(ROOT, "src", "runtime", "web", "generated");
const OUT_FILE = path.join(OUT_DIR, "defaultScenario.js");
const COUNTRY_NAMES_OUT = path.join(OUT_DIR, "countryNames.js");
const FALLBACK_COLORS_OUT = path.join(OUT_DIR, "fallbackColors.js");
const META_OUT = path.join(OUT_DIR, "defaultScenarioMeta.js");
const REGIONS_OUT = path.join(OUT_DIR, "defaultRegions.geojson");

const readJson = (rel, fallback) => {
  const file = path.join(SRC, rel);
  if (!existsSync(file)) return fallback;
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch {
    return fallback;
  }
};

const meta = readJson("scenario.json", {});
const cover = (() => {
  const file = path.join(SRC, "cover-image.bin");
  if (!existsSync(file)) return null;
  const contentType = typeof meta.coverImageContentType === "string" && meta.coverImageContentType
    ? meta.coverImageContentType
    : "image/jpeg";
  return { contentType, base64: readFileSync(file).toString("base64") };
})();

const seed = {
  meta,
  cover,
  colors: readJson("colors.json", {}),
  data: {
    game: readJson("game.json", {}),
    prompts: readJson("prompts.json", {}),
    world: readJson("world.json", {}),
    actions: readJson("storage/actions.json", []),
    advisor: readJson("storage/advisor.json", []),
    chat: readJson("storage/chat.json", []),
    events: readJson("storage/events.json", []),
  },
  // The scenario's authored cities ride in the seed (a few hundred KB); the
  // regions travel as a separate asset (see META_OUT below).
  geojson: existsSync(path.join(SRC, "cities.geojson")) ? { citiesGeojson: readJson("cities.geojson", null) } : {},
};
// Which map generation this seed carries (world.json builtInMap); the web store
// compares it against a stored library to know when Modern Day was redrawn.
const builtInMap = typeof seed.data.world?.builtInMap === "string" ? seed.data.world.builtInMap : "";

// The canonical country registry (code -> name) used by the runtime write path's
// canonicalizeCountryRef, mirroring server/country-names.json.
const countryNames = (() => {
  const file = path.join(ROOT, "server", "country-names.json");
  if (!existsSync(file)) return {};
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch {
    return {};
  }
})();

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  OUT_FILE,
  `/* AUTO-GENERATED by scripts/seed-web-defaults.mjs — do not edit. */\nexport default ${JSON.stringify(seed)};\n`,
  "utf8",
);
const regionsFile = path.join(SRC, "regions.geojson");
const regionsBundled = existsSync(regionsFile);
if (regionsBundled) writeFileSync(REGIONS_OUT, readFileSync(regionsFile));
writeFileSync(
  META_OUT,
  `/* AUTO-GENERATED by scripts/seed-web-defaults.mjs — do not edit. */
export const builtInMap = ${JSON.stringify(builtInMap)};
// Vite turns this into a hashed static asset of the web build (the map is a few
// MB, well under Cloudflare Pages' 25 MiB per-file limit); null when the seed
// directory has no regions.geojson, in which case the web store falls back to
// the stock world from the content origin.
export const regionsUrl = ${regionsBundled ? 'new URL("./defaultRegions.geojson", import.meta.url).href' : "null"};
`,
  "utf8",
);
writeFileSync(
  COUNTRY_NAMES_OUT,
  `/* AUTO-GENERATED by scripts/seed-web-defaults.mjs — do not edit. */\nexport default ${JSON.stringify(countryNames)};\n`,
  "utf8",
);

// The app-level default palette the server serves as the colors fallback for a
// scenario that ships no colors of its own (server COLORS_ASSET_CANDIDATES =
// public/assets/colors.json). Bundled separately so the fallback is immutable
// and scenario-independent, matching the server.
const fallbackColors = (() => {
  const file = path.join(ROOT, "public", "assets", "colors.json");
  if (!existsSync(file)) return {};
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch {
    return {};
  }
})();
writeFileSync(
  FALLBACK_COLORS_OUT,
  `/* AUTO-GENERATED by scripts/seed-web-defaults.mjs — do not edit. */\nexport default ${JSON.stringify(fallbackColors)};\n`,
  "utf8",
);

const kb = Math.round(Buffer.byteLength(JSON.stringify(seed)) / 1024);
console.log(`web seed: default scenario → ${path.relative(ROOT, OUT_FILE)} (${kb} KB${cover ? ", cover embedded" : ""}); map ${builtInMap || "(unstamped)"} → ${regionsBundled ? path.relative(ROOT, REGIONS_OUT) : "NOT bundled (no regions.geojson in the seed)"}; country names → ${path.relative(ROOT, COUNTRY_NAMES_OUT)} (${Object.keys(countryNames).length} entries)`);
