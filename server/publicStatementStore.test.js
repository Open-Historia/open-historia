/*! Open Historia - public statement portability regression. AGPL-3.0-or-later. */
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {normalizeWorldState,normalizeEvents} from "../src/runtime/gameState.js";
import {planPublicPublication,nextPublicStatementCursor,planPublicCancellation} from "../src/runtime/publicCommunications.js";

test("confirmed statement persists atomically with history, retains exact wording on export/import and restores with earlier generations",async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),"oh-public-"));
  process.env.OH_DATA_DIR=dir;t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const store=await import("./libraryStore.js");
  const id=store.createGame({id:"public-qa",name:"Public QA",setActive:true}).game.id;
  const game={country:"Germany",startDate:"1912-01-01",gameDate:"1912-02-15",round:9};
  const world=normalizeWorldState({ownerSchema:4,customRegions:true,socialFeed:[],simulationHistory:[{mode:"jump",round:9,fromDate:"1912-02-01",toDate:game.gameDate,eventIds:[]}]});
  const base={actions:[],chat:[],colors:{},events:[],game,world};
  store.writeRuntimeTurnState(base);
  const body="Citizens,\n\nWe seek peace. Our words do not enact a law.";
  const planned=planPublicPublication({events:[],world,game,draft:{title:"Official address",body,audience:{kind:"worldwide",target:""}},draftId:"direct:qa",expected:{country:game.country,date:game.gameDate,round:game.round},confirmed:true});
  const accepted={...base,...planned,events:normalizeEvents(planned.events)};
  store.writeRuntimeTurnState(accepted);
  const saved=normalizeEvents(store.readRuntimeJsonAsset("events").data);
  assert.equal(saved[0].publicStatement.body,body);
  assert.equal(store.readRuntimeJsonAsset("game").data.round,9);
  assert.equal(store.readRuntimeJsonAsset("world").data.socialFeed.length,0);
  assert.equal(store.readRuntimeJsonAsset("actions").data.length,0);
  const advanced={...accepted,game:{...game,round:10,gameDate:"1912-02-22"},world:{...accepted.world,publicStatementCursor:nextPublicStatementCursor(saved,accepted.world,"jump",10)}};
  store.writeRuntimeTurnState(advanced);
  const clone=store.importGameBundle(JSON.parse(JSON.stringify(store.exportGameBundle(id)))).game.id;
  const imported=store.exportGameBundle(clone).data;
  assert.deepEqual(normalizeEvents(imported.events),saved);
  assert.equal(imported.world.publicStatementCursor,10);
  store.setActiveGame(id);store.writeRuntimeTurnState(accepted);
  assert.equal(store.readRuntimeJsonAsset("world").data.publicStatementCursor,undefined);
  assert.equal(store.readRuntimeJsonAsset("events").data[0].publicStatement.body,body);
  const cancelled=planPublicCancellation({...accepted,draftId:"direct:qa",expected:{country:game.country,date:game.gameDate,round:game.round},confirmed:true});
  store.writeRuntimeTurnState({...accepted,...cancelled});
  assert.equal(store.readRuntimeJsonAsset("events").data.length,0);
  assert.deepEqual(store.readRuntimeJsonAsset("world").data.simulationHistory[0].eventIds,[]);
  assert.deepEqual(store.readRuntimeJsonAsset("world").data.cancelledPublicDrafts,["direct:qa"]);
  const cancelledClone=store.importGameBundle(JSON.parse(JSON.stringify(store.exportGameBundle(id)))).game.id;
  const cancelledData=store.exportGameBundle(cancelledClone).data;
  assert.equal(cancelledData.events.length,0);
  assert.deepEqual(normalizeWorldState(cancelledData.world).cancelledPublicDrafts,["direct:qa"]);
  store.setActiveGame(id);store.writeRuntimeTurnState(accepted);
  assert.equal(store.readRuntimeJsonAsset("events").data[0].publicStatement.body,body);
  assert.equal(store.readRuntimeJsonAsset("world").data.cancelledPublicDrafts,undefined);
  store.writeRuntimeTurnState(base);
  assert.equal(store.readRuntimeJsonAsset("events").data.length,0);
  assert.equal(store.exportGameBundle(clone).data.events[0].publicStatement.body,body);
});
