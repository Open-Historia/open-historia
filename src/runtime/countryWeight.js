// A country's weight in a land war: the points of strength the engine sizes
// its troops by (runtime/fronts/constants.js TROOPS_PER_STRENGTH: a dozen
// counters a point, a great power bringing about 24 points and a small state
// one or two). Its people, by the square root, so that a country of a billion
// is not a hundred times one of ten million on the same front: 144 million is
// 24; and what its forces have to spend (`funding`: runtime/militaryFunding.js
// forcesFunding).
//
// Never the land it holds. "remove region count power entirely, have it be
// generated by the ai for every country by the scenario designer and that then
// ships with the scenario ... if it is not pregenerated, it should just generate
// it whenever it is needed for the game for a country" (the owner, 2026-10-16).
// A country's people and its military figures are the AI's, rated against each
// other (Game/AI/militaryRating.js): for every country of a scenario by its
// designer, else as the game first needs them. A country whose people nobody
// knows yet has no weight of its own (null), and the engine counts it as the
// middle of those it knows (middleWeight) until its figures come.
//
// It lives here, and not with the turn that uses it (Game/AI/frontTurn.js,
// which hands it on under the same name), so that the Stats pane's ranking can
// show the same figure without loading the turn.
//
// Pure, and loads in plain Node.

//   funding   what its forces have to spend (runtime/militaryFunding.js forcesFunding): 1 where it is not known
export const countryWeight = ({ population = 0, funding = 1 } = {}) => {
  const people = Number(population);
  const paid = Number.isFinite(Number(funding)) && Number(funding) > 0 ? Number(funding) : 1;
  return Number.isFinite(people) && people > 0 ? Math.max(1, 2 * Math.sqrt(people / 1e6) * paid) : null;
};

// The weight a country is counted at while nobody knows its people: the middle of the weights of those whose
// people are known, else WEIGHT_UNKNOWN (an ordinary state's: some nine million people).
export const WEIGHT_UNKNOWN = 6;
export const middleWeight = (weights) => {
  const known = [...(weights ?? [])].map(Number).filter((value) => Number.isFinite(value) && value > 0).sort((a, b) => a - b);
  if (known.length === 0) return WEIGHT_UNKNOWN;
  const half = Math.floor(known.length / 2);
  return known.length % 2 === 1 ? known[half] : (known[half - 1] + known[half]) / 2;
};
